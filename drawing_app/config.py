# config.py - アプリ全体で使う定数・設定値
#
# 物理的なプリンター仕様や UI の見た目に関する数値をここに集約しています。
# 数値を変えたいときはこのファイルだけ編集すれば OK です。

import os
import sys
from pathlib import Path
from dotenv import load_dotenv

# .exe として実行中は sys.executable の隣の .env を、
# スクリプト実行中は config.py の隣の .env を読む
if getattr(sys, "frozen", False):
    _base = Path(sys.executable).parent
else:
    _base = Path(__file__).parent

_env_path = _base / ".env"
if not _env_path.exists():
    print(f"[ERROR] .env が見つかりません: {_env_path}")
    print(f"        .env.sample を参考に上記パスに .env を作成してください")
load_dotenv(_env_path, encoding="utf-8-sig")

# ---------------------------------------------------------------------------
# プリンター物理定数
# ---------------------------------------------------------------------------

MAX_PRINTER_SIZE_X = 220.0  # プリンタープレートの X 方向の最大サイズ (mm)
MAX_PRINTER_SIZE_Y = 215.0  # プリンタープレートの Y 方向の最大サイズ (mm)
GLOBAL_Y_OFFSET    = 24.0   # 自作ノズルの取り付け位置によるYオフセット (mm)
                             # ノズルが原点から 30mm ずれているため、全座標にこの値を加算する

# 実機でジョグして確認したプレート中央のノズル座標 (mm)
# デザイン（正方形）がこの点を中心になるよう自動配置される
CENTER_X = 106.70
CENTER_Y = 149.00

MATERIAL_SIZE = 5.0         # 飴1個（素材ブロック）の一辺サイズ (mm)。積み重ね時のZ方向1段分の高さでもある
JOINT_SIZE    = 2.2        # ブロック間の目地（隙間）幅 (mm)
CELL_SPACE    = MATERIAL_SIZE + JOINT_SIZE  # セル1つ分のピッチ = 6.0mm
                                             # （素材5mm + 目地1mm）

# ---------------------------------------------------------------------------
# Gコード生成定数
# ---------------------------------------------------------------------------

DRAW_Z  = -1.0   # 最下段(1層目)でノズルが素材に当たる Z 高さ (mm)。低すぎると素材を押しつぶすので注意
                 # 2層目以降は「層番号 × MATERIAL_SIZE」ぶんずつ自動で加算される（積み重ね方式）
SAFE_Z_LAYER1     = 7.0  # 1層目の退避時に DRAW_Z に加える余白 (mm)
SAFE_Z_LAYER2_PLUS = 6.0  # 2層目以降の退避時に DRAW_Z に加える余白 (mm)
                          # 積み重ねが進むほどタワーが高くなるため、層ごとに退避高さも自動で底上げされる
F_SPEED = 3600  # 移動速度 (mm/min)。G0/G1 コマンドの F パラメータに使用

# 印刷終了後にノズルを移動させる最終位置 (mm)
# 実機でジョグして確認した「プレートが一番手前に来る」座標
END_X = -13.0
END_Y = 227.0
END_Z = 50.0

# カラー名 → プリンターに送るコマンド文字列のマッピング
# OCTO90X はノズルユニットへの色指定カスタムコマンド
CMD_MAP = {
    "white":  "OCTO901",  # 白（ベース色）
    "pink":   "OCTO902",  # ピンク
    "yellow": "OCTO903",  # 黄色
}

# ---------------------------------------------------------------------------
# UI 設定
# ---------------------------------------------------------------------------

CELL_PIXEL_SIZE   = 150   # UI上で1セルを何ピクセルで表示するか
GRID_SIZE_MIN     = 2    # グリッドの最小マス目数（2×2）
GRID_SIZE_MAX     = 16   # グリッドの最大マス目数（16×16）
GRID_SIZE_DEFAULT = 3    # アプリ起動時のデフォルトマス目数

# 使用できるカラーの一覧（順序付きリスト）
# この順序がUIのボタン並び順にも使われる
COLORS = ["white", "pink", "yellow"]

# ---------------------------------------------------------------------------
# OctoPrint 接続設定
# ---------------------------------------------------------------------------

OCTOPRINT_URL     = "http://3dz5.local"
OCTOPRINT_API_KEY = os.environ.get("OCTOPRINT_API_KEY", "")